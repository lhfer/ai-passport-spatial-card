/**
 * Emits an LVGL 9 `lv_image_dsc_t` C file in exactly the layout of the placeholders that
 * `firmware/ai-passport-card/assets/images/theme_*.c` shipped with: 32 bytes per line,
 * `0x%02x` separated by commas, a trailing comma on every line, a 4-byte aligned map array and a
 * `const lv_image_dsc_t theme_<id>` descriptor (RGB565, stride = 2 × width).
 */
import { rgb565Bytes } from './raster.ts';

export interface LvglImageOptions {
  /** C symbol, e.g. `theme_neon_city`. */
  symbol: string;
  width: number;
  height: number;
  /** One RGB565 value per pixel, row-major. */
  pixels: Uint16Array;
  /** Emit big-endian (byte-swapped) pixel words. Default little-endian (LVGL native on ESP32). */
  swapBytes?: boolean;
  /** Provenance line for the header comment. */
  generatedBy?: string;
}

export const LVGL_BYTES_PER_LINE = 32;

export function symbolForTheme(themeId: string): string {
  return `theme_${themeId.replace(/[^a-z0-9]+/gi, '_').toLowerCase()}`;
}

export function emitLvglImageC(opts: LvglImageOptions): string {
  const { symbol, width, height, pixels } = opts;
  if (pixels.length !== width * height) {
    throw new Error(`pixel count ${pixels.length} does not match ${width}x${height}`);
  }
  const bytes = rgb565Bytes(pixels, opts.swapBytes ?? false);
  const stride = width * 2;
  const lines: string[] = [];
  lines.push(
    `// Generated by ${opts.generatedBy ?? 'hub/tools/render-screens.ts'} (pnpm screens) — do not edit. RGB565 ${opts.swapBytes ? 'big-endian (byte-swapped)' : 'little-endian'}, ${width}x${height}.`,
  );
  lines.push('#include "lvgl.h"');
  lines.push('');
  lines.push(`static const uint8_t ${symbol}_map[] __attribute__((aligned(4))) = {`);
  for (let i = 0; i < bytes.length; i += LVGL_BYTES_PER_LINE) {
    const chunk = bytes.subarray(i, Math.min(i + LVGL_BYTES_PER_LINE, bytes.length));
    let line = '  ';
    for (let k = 0; k < chunk.length; k++) {
      line += `0x${chunk[k]!.toString(16).padStart(2, '0')},`;
    }
    lines.push(line);
  }
  lines.push('};');
  lines.push('');
  lines.push(`const lv_image_dsc_t ${symbol} = {`);
  lines.push('  .header.magic = LV_IMAGE_HEADER_MAGIC,');
  lines.push('  .header.cf = LV_COLOR_FORMAT_RGB565,');
  lines.push('  .header.flags = 0,');
  lines.push(`  .header.w = ${width},`);
  lines.push(`  .header.h = ${height},`);
  lines.push(`  .header.stride = ${stride},`);
  lines.push(`  .data_size = ${bytes.length},`);
  lines.push(`  .data = ${symbol}_map,`);
  lines.push('};');
  lines.push('');
  return lines.join('\n');
}
