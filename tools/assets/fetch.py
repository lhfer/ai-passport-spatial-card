#!/usr/bin/env python3
"""Download CC0 assets for the worlds and register them in assets/worlds/THIRD_PARTY_ASSETS.md.

    fetch.py polyhaven <id> --type model|texture|hdri [--res 1k|2k|4k] --world <world-id> [--usdz name]
    fetch.py kenney <asset-slug> --world <world-id>
    fetch.py ambientcg <AssetID> [--res 1K|2K] --world <world-id>

Downloads land in assets/worlds/raw/<source>/<id>/ (git-ignored). Every file is hashed (SHA-256) and
appended to the registry with its source URL and license. `--usdz` runs tools/assets/to_usdz.py on a
downloaded model and writes visionos/SpatialCard/Resources/worlds/<world-id>/<name>.usdz.
"""
import argparse
import datetime as dt
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import urllib.request
import zipfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
RAW = REPO / "assets" / "worlds" / "raw"
REGISTRY = REPO / "assets" / "worlds" / "THIRD_PARTY_ASSETS.md"
RESOURCES = REPO / "visionos" / "SpatialCard" / "Resources" / "worlds"
BLENDER = "/Applications/Blender.app/Contents/MacOS/Blender"
UA = "SpatialCard-assets/1.0 (macOS; contact: dev@letsvibe)"

LICENSES = {
    "polyhaven": ("CC0 1.0", "https://polyhaven.com/license"),
    "kenney": ("CC0 1.0", "https://kenney.nl/support"),
    "ambientcg": ("CC0 1.0", "https://ambientcg.com/view?id=%s"),
}


def http(url: str, dest: Path | None = None) -> bytes | Path:
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=120) as r:
        data = r.read()
    if dest is None:
        return data
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_bytes(data)
    return dest


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def register(source: str, asset_id: str, url: str, files: list[Path], world: str, note: str = "") -> None:
    REGISTRY.parent.mkdir(parents=True, exist_ok=True)
    if not REGISTRY.exists():
        REGISTRY.write_text(
            "# Third-party assets (all CC0)\n\n"
            "Every file used by the worlds, with its origin and hash. CC0 requires no attribution; the table exists so an asset\n"
            "can be traced, re-downloaded or replaced. Generated by `tools/assets/fetch.py`; do not edit rows by hand.\n\n"
            "| Date | World | Source | Asset | License | URL | Files (SHA-256 prefix) | Note |\n|---|---|---|---|---|---|---|---|\n",
            encoding="utf-8",
        )
    lic, lic_url = LICENSES[source]
    if "%s" in lic_url:
        lic_url = lic_url % asset_id
    hashes = ", ".join(f"`{f.name}` {sha256(f)[:12]}" for f in files if f.is_file())
    row = f"| {dt.date.today().isoformat()} | {world} | {source} | {asset_id} | [{lic}]({lic_url}) | {url} | {hashes} | {note} |\n"
    with open(REGISTRY, "a", encoding="utf-8") as f:
        f.write(row)
    print(f"[registry] {source}/{asset_id}: {len(files)} files")


def to_usdz(src: Path, world: str, name: str, scale: float = 1.0, merge: bool = True, max_texture: int = 2048, decimate: float = 1.0) -> Path:
    out = RESOURCES / world / f"{name}.usdz"
    cmd = [BLENDER, "-b", "-P", str(REPO / "tools" / "assets" / "to_usdz.py"), "--", str(src), str(out), "--scale", str(scale), "--max-texture", str(max_texture), "--decimate", str(decimate)]
    if merge:
        cmd.append("--merge")
    r = subprocess.run(cmd, capture_output=True, text=True)
    lines = [l for l in (r.stdout + r.stderr).splitlines() if "[to_usdz]" in l or "Error" in l or "Traceback" in l]
    print("\n".join(lines[-4:]))
    if not out.exists():
        sys.exit(f"usdz conversion failed for {src}")
    return out


# --- Poly Haven -------------------------------------------------------------------------------

def polyhaven(args):
    files = json.loads(http(f"https://api.polyhaven.com/files/{args.id}"))
    dest = RAW / "polyhaven" / args.id
    got: list[Path] = []
    if args.type == "hdri":
        entry = files["hdri"][args.res]["hdr"]
        got.append(http(entry["url"], dest / f"{args.id}_{args.res}.hdr"))
        url = entry["url"]
    elif args.type == "texture":
        url = f"https://polyhaven.com/a/{args.id}"
        for key in ("Diffuse", "nor_gl", "Rough", "AO", "Metal", "arm"):
            if key in files and args.res in files[key]:
                fmt = "jpg" if "jpg" in files[key][args.res] else next(iter(files[key][args.res]))
                entry = files[key][args.res][fmt]
                got.append(http(entry["url"], dest / f"{args.id}_{key}_{args.res}.{fmt}"))
    else:  # model: glTF + bin + textures at the requested resolution
        entry = files["gltf"][args.res]["gltf"]
        url = entry["url"]
        got.append(http(url, dest / f"{args.id}_{args.res}.gltf"))
        for rel, inc in (entry.get("include") or {}).items():
            got.append(http(inc["url"], dest / rel))
    register("polyhaven", args.id, url, got, args.world, note=f"{args.type} {args.res}")
    if args.type in ("hdri", "texture"):
        # Runtime assets: copied into the app's world folder (HDRI for IBL / sky, texture sets for procedural meshes).
        target = RESOURCES / args.world
        target.mkdir(parents=True, exist_ok=True)
        for f in got:
            shutil.copy2(f, target / f.name)
        print(f"[fetch] copied {len(got)} files → {target.relative_to(REPO)}")
    if args.type == "model" and args.usdz:
        out = to_usdz(dest / f"{args.id}_{args.res}.gltf", args.world, args.usdz, scale=args.scale, merge=not args.no_merge, max_texture=args.max_texture, decimate=args.decimate)
        print(f"[fetch] usdz → {out.relative_to(REPO)}")


# --- Kenney -----------------------------------------------------------------------------------

def kenney(args):
    page = http(f"https://kenney.nl/assets/{args.slug}").decode("utf-8", "replace")
    m = re.search(r'https://kenney\.nl/media/pages/assets/[^"]+\.zip', page)
    if not m:
        sys.exit("no zip link on the Kenney page")
    url = m.group(0)
    dest = RAW / "kenney" / args.slug
    zpath = http(url, dest / Path(url).name)
    with zipfile.ZipFile(zpath) as z:
        z.extractall(dest)
    register("kenney", args.slug, url, [zpath], args.world, note="kit zip (glTF/GLB inside)")
    print(f"[fetch] kenney {args.slug} → {dest.relative_to(REPO)}")


# --- ambientCG --------------------------------------------------------------------------------

def ambientcg(args):
    url = f"https://ambientcg.com/get?file={args.id}_{args.res}-JPG.zip"
    dest = RAW / "ambientcg" / args.id
    zpath = http(url, dest / f"{args.id}_{args.res}-JPG.zip")
    with zipfile.ZipFile(zpath) as z:
        z.extractall(dest)
    register("ambientcg", args.id, url, [zpath], args.world, note=f"PBR set {args.res}")
    print(f"[fetch] ambientcg {args.id} → {dest.relative_to(REPO)}")


def convert(args):
    src = Path(args.input)
    if not src.is_absolute():
        src = REPO / src
    out = to_usdz(src, args.world, args.name, scale=args.scale, merge=not args.no_merge, max_texture=args.max_texture, decimate=args.decimate)
    print(f"[fetch] usdz → {out.relative_to(REPO)}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("polyhaven")
    p.add_argument("id"); p.add_argument("--type", choices=("model", "texture", "hdri"), required=True)
    p.add_argument("--res", default="1k"); p.add_argument("--world", required=True)
    p.add_argument("--usdz", help="convert the model and write Resources/worlds/<world>/<name>.usdz")
    p.add_argument("--scale", type=float, default=1.0); p.add_argument("--no-merge", action="store_true"); p.add_argument("--max-texture", type=int, default=2048)
    p.add_argument("--decimate", type=float, default=1.0, help="Blender decimate ratio for dense scans (e.g. 0.35)")
    p.set_defaults(fn=polyhaven)
    k = sub.add_parser("kenney"); k.add_argument("slug"); k.add_argument("--world", required=True); k.set_defaults(fn=kenney)
    a = sub.add_parser("ambientcg"); a.add_argument("id"); a.add_argument("--res", default="1K"); a.add_argument("--world", required=True); a.set_defaults(fn=ambientcg)
    c = sub.add_parser("convert", help="convert an already-downloaded model (e.g. a Kenney GLB) to Resources/worlds/<world>/<name>.usdz")
    c.add_argument("input"); c.add_argument("--world", required=True); c.add_argument("--name", required=True)
    c.add_argument("--scale", type=float, default=1.0); c.add_argument("--no-merge", action="store_true"); c.add_argument("--max-texture", type=int, default=2048)
    c.add_argument("--decimate", type=float, default=1.0); c.set_defaults(fn=convert)
    args = ap.parse_args()
    args.fn(args)


if __name__ == "__main__":
    main()
